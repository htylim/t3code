import { useNewThreadHandler } from "./useHandleNewThread";

describe("useNewThreadHandler", () => {
  it.each([
    ["fresh", null],
    [
      "reused",
      {
        draftId: "draft-existing",
        environmentId: "environment-ssh",
        promotedTo: null,
        threadId: "thread-existing",
      },
    ],
  ] as const)(
    "seeds configured model, effort, and permission into a %s draft",
    async (_, draft) => {
      testState.reset(draft);
      const defaults: NewChatDefaults = {
        modelSelection: {
          instanceId: ProviderInstanceId.make("codex_personal"),
          model: "gpt-6-astra",
          options: [{ id: "reasoningEffort", value: "high" }],
        },
        runtimeMode: "approval-required",
      };
      testState.settings.newChatDefaults = defaults;
      const pending = useNewThreadHandler()({
        environmentId: "environment-ssh",
        projectId: "project-remote",
      } as never);
      testState.completeProjectFileRead(null);
      const opened = await pending;
      expect(testState.draftStore.setModelSelection).toHaveBeenCalledWith(
        opened?.draftId,
        defaults.modelSelection,
        { replaceOptions: true },
      );
      expect(testState.draftStore.setLogicalProjectDraftThreadId).toHaveBeenCalledWith(
        "remote-project",
        expect.anything(),
        opened?.draftId,
        expect.objectContaining({ runtimeMode: "approval-required" }),
      );
    },
  );

  it.each([
    ["new", null],
    [
      "reusable",
      {
        draftId: "draft-existing",
        environmentId: "environment-ssh",
        promotedTo: null,
        threadId: "thread-existing",
      },
    ],
  ])("abandons a delayed %s draft open when the user navigates elsewhere", async (_, draft) => {
    testState.reset(draft);
    const openThread = useNewThreadHandler();
    const pendingOpen = openThread(
      { environmentId: "environment-ssh", projectId: "project-remote" } as never,
      { replace: true },
    );

    testState.router.state.location.href = "/usage";
    testState.completeProjectFileRead(null);
    await pendingOpen;

    expect(testState.router.state.location.href).toBe("/usage");
    expect(testState.router.navigate).not.toHaveBeenCalled();
    expect(testState.draftStore.setLogicalProjectDraftThreadId).not.toHaveBeenCalled();
  });
});
